#!/usr/bin/env python
"""Paper-2 appendix table: addendum G's whole-panel estimand G2 on the benchmark leaderboard rows.

G2 is computed by the frozen scripts/analyze_wholepanel.py (sha 73bfea8b, addendum G c7e04919); this
script only formats it. Every leaderboard row's data predate the addendum, so every G2 here is post hoc.
Rows follow bench_registry.MODELS (the leaderboard order). The BM-2c rows carry G2 in tab_bm2c_ladder.

Writes paper2/latex/sections/tab_g2_wholepanel.tex (whole file).   --check = fail if it would change.
"""
from __future__ import annotations
import argparse, json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from analyze_fm1 import all_dates, build_covariates  # noqa: E402
from analyze_wholepanel import g2, WINDOW_END, BENCH  # noqa: E402
from bench_registry import MODELS  # noqa: E402
from hindsight_paths import REPO  # noqa: E402

TEX = REPO / "hindsight/paper2/latex/sections/tab_g2_wholepanel.tex"


def m(x: float) -> str:
    return f"{x:+.1f}".replace("-", "$-$")


def e2_sig(key: str):
    e = json.loads((BENCH / key / f"{key}_row.json").read_text())["E2_date_trigger"]
    if e.get("gated"):
        return None
    return e["ci95"][0] > 0 or e["ci95"][1] < 0, e["est"] > 0


def build() -> str:
    cov = build_covariates([d for d in all_dates() if d <= WINDOW_END])
    rows = []
    for mm in MODELS:
        k = mm["key"]; g = g2(k, cov); s = e2_sig(k)
        read = {"TRIGGER": r"\textbf{trigger}", "NEG*": r"\textbf{neg.}", "null": "null",
                "insufficient coverage": r"---\textsuperscript{c}"}[g["reading"]]
        e2 = "gated" if s is None else ("trigger" if s[0] and s[1] else ("neg." if s[0] else "null"))
        coef = r"\multicolumn{2}{c}{---}" if g["reading"] == "insufficient coverage" else \
            f"{m(g['coef'] * 100)} [{m(g['ci95'][0] * 100)}, {m(g['ci95'][1] * 100)}] & " + f"{g['t']:+.2f}".replace("-", "$-$")
        rows.append(f"{mm['tex']} & {g['n_dates']} ({g['n_recession']}) & {coef} & {read} & {e2} \\\\")
    return "\n".join([
        "% Generated by scripts/make_g2_table.py from the frozen analyze_wholepanel.py -- do not hand-edit.",
        r"\begin{table}[tbp]", r"\centering", r"\small",
        r"\resizebox{\linewidth}{!}{%", r"\begin{tabular}{@{}lrrrll@{}}", r"\toprule",
        r"Model & Dates (recession) & G2 (pp) [95\% CI] & $t$ & G2 reading & E2 reading \\", r"\midrule",
        *rows, r"\bottomrule", r"\end{tabular}}",
        r"\caption{Whole-panel date trigger G2 (addendum G, post hoc for every row shown): the USREC coefficient in a "
        r"regression of the per-date D-minus-M bearish share on the NBER recession indicator, all panel dates to 2023-12, "
        r"HAC(6) errors; reading at $|t| \geq 1.96$. E2 reading from the frozen row (95\% CI). "
        r"\textsuperscript{c}~fewer than 200 window dates (reduced tier), no reading.}",
        r"\label{tab:g2}", r"\end{table}", ""])


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--check", action="store_true"); a = ap.parse_args()
    new = build(); old = TEX.read_text() if TEX.exists() else None
    if a.check:
        sys.exit(0 if new == old else "CHECK FAIL: tab_g2_wholepanel.tex would change")
    TEX.write_text(new); print(f"wrote {TEX.name} ({'changed' if new != old else 'unchanged'})")


if __name__ == "__main__":
    main()
