#!/usr/bin/env python3
"""RV-1 per-date breakdown of the pre-shock contrast, as RV1_prereg.md section A commits ("the paper reports
PS per date"). Reporting only: for each SHOCK date, D-arm minus M-arm bearish share (replicates pooled),
against the CONTROL-set mean of the same quantity. Separate from the frozen analyze_rv1.py so its hash is kept."""
import json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
import analyze_rv1 as A  # noqa: E402

spec = json.loads((A.H / "prereg/RV1_preshock_dates.json").read_text())["primary"]
S = [r["date"] for r in spec["SHOCK"]]; C = spec["CONTROL"]
L = ["# RV-1 pre-shock per date (generated by rv1_preshock_perdate.py; do not hand-edit)", "",
     "Per-date D-minus-M bearish share, pp (replicates pooled); CONTROL row = mean over the 72 control dates.", "",
     "| model | " + " | ".join(S) + " | CONTROL mean |", "|---|" + "---|" * (len(S) + 1)]
for m in ("flash", "pro", "deepseek"):
    root = A.MODELS[m]; reps = sorted(set(A.reps_of(root, "D")) & set(A.reps_of(root, "M")))
    D = A.pool([A.load(root, "D", r) for r in reps]); M = A.pool([A.load(root, "M", r) for r in reps])
    sh = lambda X, d: X[d].count("-") / len(X[d]) if X.get(d) else float("nan")
    h = {d: (sh(D, d) - sh(M, d)) * 100 for d in S + C}
    cm = sum(h[d] for d in C) / len(C)
    L.append(f"| {m} | " + " | ".join(f"{h[d]:+.0f}" for d in S) + f" | {cm:+.1f} |")
txt = "\n".join(L) + "\n"; print(txt); (A.H / "outputs/review/rv1_preshock_perdate.md").write_text(txt)
