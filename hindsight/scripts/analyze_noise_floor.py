#!/usr/bin/env python3
"""BM-2c noise floor (post hoc, exploratory; fixes in a script the inline check run on 2026-09-23).

Runs the same same-date paired test used for tier contrasts (E2 difference with the date-level bootstrap,
B = 10,000, seed 2026; G2 difference = USREC slope of the per-date (D-M) difference, dates <= 2023-12,
HAC 6) on pairs of replicates of ONE model under ONE serving configuration. Under the null of no
difference these should rarely be flagged. Also reports the tier contrasts restricted to rep1 of each
row, so that replicate count does not differ between the sides.

    python scripts/analyze_noise_floor.py [--md outputs/bench/NOISE_FLOOR.md]
"""
from __future__ import annotations
import argparse, json, sys
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).parent))
from analyze_fm1 import CRISIS, CALM_YEARS, all_dates, gap, build_covariates  # noqa: E402
import statsmodels.api as sm  # noqa: E402

BENCH = Path(__file__).resolve().parents[1] / "outputs/bench"
REP_PAIRS = [("gemini-2.5-flash", "rep1", "rep2"), ("gemini-2.5-flash", "rep1", "rep3"), ("gemini-2.5-flash", "rep2", "rep3"),
             ("qwen3.6-27b-fp8", "rep1", "rep2"), ("qwen3.6-27b-bf16", "rep1", "rep2")]
TIER_PAIRS = [("qwen3.6-27b-fp8", "qwen3.6-27b-bf16"), ("qwen3.6-27b-awq", "qwen3.6-27b-bf16"), ("tulu3-70b-rlvr-awq", "tulu3-70b-rlvr-fp8dyn")]
# recipe contrasts (all replicates pooled, as in the rows): the yardstick the tier contrasts are compared with
RECIPE_PAIRS = [("qwen3-30b-a3b-thinking-2507-fp8dyn", "qwen3-30b-a3b-fp8dyn"), ("qwen3-30b-a3b-instruct-2507-fp8dyn", "qwen3-30b-a3b-fp8dyn"),
                ("llama-3.3-70b-awq", "llama-3.1-70b-awq"), ("llama-3.3-70b-fp8dyn", "llama-3.1-70b-fp8dyn"),
                ("llama-3.1-nemotron-70b-awq", "llama-3.1-70b-awq")]
dates = all_dates(); crisis = [d for d in dates if d in CRISIS]; calm = [d for d in dates if d[:4] in CALM_YEARS]
cov = build_covariates([d for d in dates if d <= "2023-12-31"])


def arms(k, rep):
    o = {}
    for a in "DM":
        bd = {}
        for n in (BENCH / k / a).glob(f"{rep}/*"):
            f = n / "01_sketches_valid.json"
            if f.exists():
                bd.setdefault(n.name, []).extend(s["direction"] for s in json.loads(f.read_text()) if s.get("direction") in ("+", "-"))
        o[a] = bd
    return o


def e2(A, c, q):
    return gap(A["D"], c, q) - gap(A["M"], c, q)


def share(bd):
    return {d: v.count("-") / len(v) for d, v in bd.items() if v}


def test(A, B):
    rng = np.random.default_rng(2026); c, q = np.array(crisis), np.array(calm); out = []
    for _ in range(10_000):
        cs, qs = list(rng.choice(c, len(c))), list(rng.choice(q, len(q))); out.append(e2(A, cs, qs) - e2(B, cs, qs))
    Da, Ma, Db, Mb = share(A["D"]), share(A["M"]), share(B["D"]), share(B["M"])
    df = cov.copy()
    df["y"] = [(Da.get(d, np.nan) - Ma.get(d, np.nan)) - (Db.get(d, np.nan) - Mb.get(d, np.nan)) for d in df.index]
    df = df.dropna(subset=["y", "usrec"])
    f = sm.OLS(df["y"].values, sm.add_constant(df[["usrec"]].values)).fit(cov_type="HAC", cov_kwds={"maxlags": 6})
    return (e2(A, crisis, calm) - e2(B, crisis, calm)) * 100, np.percentile(out, 2.5) * 100, np.percentile(out, 97.5) * 100, float(f.tvalues[1])


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--md", type=Path); a = ap.parse_args()
    L = ["# BM-2c noise floor (post hoc; generated by analyze_noise_floor.py, do not hand-edit)", "",
         "Same model, same serving, different replicate: the paired test used for tier contrasts.", "",
         "| model | pair | E2 diff pp [95% CI] | flagged (E2) | G2-diff t (HAC 6) | flagged (G2) |", "|---|---|---|---|---|---|"]
    nE = nG = 0; mx = 0.0
    for k, r1, r2 in REP_PAIRS:
        d, lo, hi, t = test(arms(k, r1), arms(k, r2)); fe = lo > 0 or hi < 0; fg = abs(t) >= 1.96
        nE += fe; nG += fg; mx = max(mx, abs(d))
        L.append(f"| {k} | {r1}-{r2} | {d:+.1f} [{lo:+.1f}, {hi:+.1f}] | {'yes' if fe else 'no'} | {t:+.2f} | {'yes' if fg else 'no'} |")
    L += ["", f"flagged: E2 {nE}/{len(REP_PAIRS)}, G2 {nG}/{len(REP_PAIRS)}; largest |E2 diff| {mx:.1f} pp (the floor used by addenda H and I)", "",
          "Tier contrasts restricted to rep1 of each row:", "", "| A - B | E2 diff pp [95% CI] | G2-diff t |", "|---|---|---|"]
    for x, y in TIER_PAIRS:
        d, lo, hi, t = test(arms(x, "rep1"), arms(y, "rep1"))
        L.append(f"| {x} - {y} | {d:+.1f} [{lo:+.1f}, {hi:+.1f}] | {t:+.2f} |")
    L += ["", "Recipe contrasts, all replicates pooled (for scale):", "", "| A - B | E2 diff pp [95% CI] | G2-diff t |", "|---|---|---|"]
    for x, y in RECIPE_PAIRS:
        d, lo, hi, t = test(arms(x, "rep*"), arms(y, "rep*"))
        L.append(f"| {x} - {y} | {d:+.1f} [{lo:+.1f}, {hi:+.1f}] | {t:+.2f} |")
    txt = "\n".join(L) + "\n"; print(txt)
    if a.md: a.md.write_text(txt)


if __name__ == "__main__":
    main()
