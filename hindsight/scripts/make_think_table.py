#!/usr/bin/env python
"""paper2 table from outputs/review/think_traces/think_traces_rows.json (generated; --check = drift gate)."""
import json, sys
from hindsight_paths import REPO
SRC = REPO / "hindsight/outputs/review/think_traces/think_traces_rows.json"
DST = REPO / "hindsight/paper2/latex/sections/tab_think_traces.tex"
NAME = {"qwen3-30b-a3b-fp8dyn": "Qwen3-30B-A3B (2025-04 release)", "qwen3-30b-a3b-thinking-2507-fp8dyn": "Qwen3-30B-A3B Thinking 2507, FP8",
        "qwen3-30b-a3b-thinking-2507-bf16": "\\quad BF16", "qwen3-30b-a3b-thinking-2507-bf16-r2": "\\quad BF16, second run",
        "qwen3-30b-a3b-thinking-2507-awq": "\\quad AWQ-INT4", "qwen3-30b-a3b-thinking-2507-gptq-w4a16": "\\quad GPTQ-INT4",
        "qwen3-30b-a3b-thinking-2507-int8-w8a8": "\\quad INT8", "qwen3-30b-a3b-thinking-2507-fp8block": "\\quad block-FP8",
        "qwen3-30b-a3b-thinking-2507-bf16-fp16act": "\\quad BF16, fp16 activations",
        "qwen3.6-27b-fp8": "Qwen3.6-27B, FP8", "qwen3.6-27b-awq": "\\quad AWQ-INT4", "qwen3.6-27b-bf16": "\\quad BF16",
        "qwen3.6-35b-a3b-fp8": "Qwen3.6-35B-A3B, FP8", "olmo3-7b-think": "Olmo 3 7B Think", "r1-distill-llama-70b-awq": "R1-distill Llama 70B"}
ORDER = list(NAME)
def main():
    rows = {r["model"]: r for r in json.loads(SRC.read_text())}
    f = lambda x: "---" if x != x else f"{x:.2f}"
    L = ["% Generated by scripts/make_think_table.py from outputs/review/think_traces/think_traces_rows.json -- do not hand-edit.",
         "\\begin{table}[tbp]", "\\centering", "\\footnotesize", "\\setlength{\\tabcolsep}{4pt}",
         "\\resizebox{\\linewidth}{!}{%", "\\begin{tabular}{@{}lrrrrr@{}}", "\\toprule",
         "Row & \\multicolumn{2}{c}{episode named, crisis dates} & \\multicolumn{2}{c}{year named, masked arm} & masked bearish \\\\",
         " & D arm & M arm & crisis & calm & named / unnamed \\\\", "\\midrule"]
    for k in ORDER:
        if k not in rows: continue
        r = rows[k]
        L.append(f"{NAME[k]} & {f(r['D_vocab_c'])} & {f(r['M_vocab_c'])} & {f(r['M_selfloc_c'])} & {f(r['M_selfloc_q'])} & {f(r['M_bear_selfloc'])} / {f(r['M_bear_no'])} \\\\")
    L += ["\\bottomrule", "\\end{tabular}}",
          "\\caption{What the reasoning trace does with the date (rows whose raw responses keep the trace; 258 cells per arm). "
          "Episode named: share of crisis-date traces naming that date's own episode (Lehman or subprime; pandemic, COVID or lockdown; "
          "inflation surge or Fed hikes), with the date stated (D) and without it (M). Year named: share of masked-arm traces that name "
          "any calendar year, on crisis and calm dates; across rows, the named year is within one year of the true one in 4--47\\% of "
          "those traces. Masked bearish: masked-arm bearish share across all 258 dates, on cells whose trace names a year against cells whose trace names none.}",
          "\\label{tab:think}", "\\end{table}", ""]
    txt = "\n".join(L)
    if "--check" in sys.argv:
        sys.exit(0 if DST.exists() and DST.read_text() == txt else 1)
    DST.write_text(txt); print("wrote", DST.name)
if __name__ == "__main__":
    main()
