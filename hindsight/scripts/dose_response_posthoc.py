#!/usr/bin/env python3
"""Post hoc companion to the frozen analyze_dose_response.py (addendum I): the same contrasts against
I3 (the second BF16 run), because the frozen design uses I1 as its
only reference and I1's E2 sits at the top of the two BF16 runs. Reporting only: no reading is attached,
and the frozen script (and its hash) is untouched. Writes outputs/bench/DOSE_RESPONSE_POSTHOC.md.

    python scripts/dose_response_posthoc.py
"""
from __future__ import annotations
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
import analyze_dose_response as dr  # noqa: E402

OUT = dr.BENCH / "DOSE_RESPONSE_POSTHOC.md"


def fmt(c):
    e2 = "gated" if c["E2"] is None else "%+.1f [%+.1f, %+.1f]" % c["E2"]
    return "%s | %+.1f (t %+.2f) | %+.1f [%+.1f, %+.1f]" % ((e2,) + c["DATE"] + c["BASE"])


def main():
    keys = {r[0]: r[1] for r in dr.RUNGS}
    lines = ["# Addendum I, post hoc: contrasts against I3 (generated by dose_response_posthoc.py; do not hand-edit)", "",
             "Same estimators as the frozen script (date bootstrap B=10,000, seed 2026; DATE = USREC slope of the",
             "per-date D-arm difference, HAC 6). Post hoc, no reading attached; the frozen readings use I1 only.", "",
             "| contrast | E2 pp [95% CI] | DATE pp (t) | BASE pp [95% CI] |", "|---|---|---|---|"]
    for r in ["I1", "I2", "I4", "I5", "I6", "I7"]:
        lines.append(f"| {r} minus I3 | " + fmt(dr.contrast(keys[r], keys["I3"])) + " |")
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
