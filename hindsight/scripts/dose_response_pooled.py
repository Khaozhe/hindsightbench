#!/usr/bin/env python3
"""Post hoc companion to the frozen analyze_dose_response.py (addendum I): every rung against the POOLED
BF16 reference (I1 and I3 generations pooled per date, two replicates), with the same estimators.
Rationale: I1 and I3 are two runs of one configuration on one box and differ by 21.5pp on E2; the
pooled run is the unbiased reference and halves the reference's own run-to-run variance.
Reporting only; the frozen script and its readings are untouched. Writes outputs/bench/DOSE_RESPONSE_POOLED.md.

    python scripts/dose_response_pooled.py
"""
from __future__ import annotations
import sys
import numpy as np
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
import analyze_dose_response as dr  # noqa: E402
from analyze_fm1 import gap  # noqa: E402

OUT = dr.BENCH / "DOSE_RESPONSE_POOLED.md"


def pooled(arm):
    a, b = dr.by_date(dr.P + "bf16", arm), dr.by_date(dr.P + "bf16-r2", arm)
    o = {}
    for d in set(a) | set(b):
        o[d] = a.get(d, []) + b.get(d, [])
    return o


def share(bd):
    return {d: sum(1 for x in v if x == "-") / len(v) for d, v in bd.items() if v}


def contrast_vs_pooled(k):
    A = {a: dr.by_date(k, a) for a in "DM"}; R = {a: pooled(a) for a in "DM"}
    rng = np.random.default_rng(dr.SEED); c, q = np.array(dr.crisis), np.array(dr.calm); out = np.empty(dr.B)
    e2 = lambda X, cs, qs: gap(X["D"], cs, qs) - gap(X["M"], cs, qs)
    for i in range(dr.B):
        cs, qs = list(rng.choice(c, len(c))), list(rng.choice(q, len(q))); out[i] = e2(A, cs, qs) - e2(R, cs, qs)
    dE2 = (e2(A, dr.crisis, dr.calm) - e2(R, dr.crisis, dr.calm)) * 100
    Da, Dr = share(A["D"]), share(R["D"])
    dDATE, tDATE = dr.hac({d: Da[d] - Dr[d] for d in Da if d in Dr})
    Ma, Mr = share(A["M"]), share(R["M"]); common = sorted(set(Ma) & set(Mr))
    diffs = np.array([Ma[d] - Mr[d] for d in common]); rng2 = np.random.default_rng(dr.SEED)
    boots = [diffs[rng2.integers(0, len(diffs), len(diffs))].mean() for _ in range(dr.B)]
    return {"E2": (dE2, np.percentile(out, 2.5) * 100, np.percentile(out, 97.5) * 100), "DATE": (dDATE, tDATE),
            "BASE": (diffs.mean() * 100, np.percentile(boots, 2.5) * 100, np.percentile(boots, 97.5) * 100)}


def main():
    keys = {r[0]: r[1] for r in dr.RUNGS}
    R = {a: pooled(a) for a in "DM"}
    e2_ref = (gap(R["D"], dr.crisis, dr.calm) - gap(R["M"], dr.crisis, dr.calm)) * 100
    L = ["# Addendum I, post hoc: contrasts against the POOLED BF16 reference (I1+I3) (generated by dose_response_pooled.py; do not hand-edit)", "",
         f"Pooled reference E2 = {e2_ref:+.1f} pp (I1 +29.5, I3 +8.0). Same estimators as the frozen script. Post hoc; the frozen readings use I1 only.", "",
         "| contrast | E2 pp [95% CI] | DATE pp (t) | BASE pp [95% CI] | beyond floor? |", "|---|---|---|---|---|"]
    for r in ["I1", "I3", "I2", "I4", "I5", "I6", "I7"]:
        c = contrast_vs_pooled(keys[r])
        beyond = []
        if c["E2"][1] > 0 or c["E2"][2] < 0: beyond.append("E2")
        if abs(c["DATE"][1]) >= 1.96: beyond.append("DATE")
        if c["BASE"][1] > 0 or c["BASE"][2] < 0: beyond.append("BASE")
        L.append(f"| {r} minus pooled | {c['E2'][0]:+.1f} [{c['E2'][1]:+.1f}, {c['E2'][2]:+.1f}] | {c['DATE'][0]:+.1f} (t {c['DATE'][1]:+.2f}) | "
                 f"{c['BASE'][0]:+.1f} [{c['BASE'][1]:+.1f}, {c['BASE'][2]:+.1f}] | {', '.join(beyond) or '—'} |")
    OUT.write_text("\n".join(L) + "\n"); print("\n".join(L))


if __name__ == "__main__":
    main()
