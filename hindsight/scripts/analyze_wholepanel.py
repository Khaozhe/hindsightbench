#!/usr/bin/env python3
"""BM-2c addendum G: whole-panel date-trigger estimand (G2).

For each row, y_t = bearish share of arm D at date t minus bearish share of arm M at date t, over every
panel date t <= 2023-12-31 with both cells present; OLS of y_t on a constant and the NBER recession
indicator USREC_t (the regressor paper 1 found decisive for R-M, t = 3.76), HAC standard errors with
6 lags (paper 1's specification). G2 = the USREC coefficient; G2 triggers when t >= 1.96, is NEG*
when t <= -1.96, null otherwise. Only rows with a finished <key>_row.json are read.

    python scripts/analyze_wholepanel.py                 # all finished rows
    python scripts/analyze_wholepanel.py --keys a b      # selected rows
    python scripts/analyze_wholepanel.py --md out.md     # also write a markdown table
"""
from __future__ import annotations
import argparse, json, sys
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).parent))
from analyze_fm1 import all_dates, build_covariates  # noqa: E402
from hindsight_paths import REPO  # noqa: E402
import statsmodels.api as sm  # noqa: E402

BENCH = REPO / "hindsight/outputs/bench"
WINDOW_END = "2023-12-31"
HAC_LAGS = 6
T_CRIT = 1.96
MIN_DATES = 200          # of the 228 window dates; below this the row gets no G2 reading
# rows whose data were seen before this addendum was frozen (2026-09-23): G2 is post hoc for them
PROSPECTIVE = {"tulu3-70b-sft-fp8dyn", "tulu3-70b-dpo-fp8dyn", "tulu3-70b-rlvr-fp8dyn", "hermes3-70b-fp8", "tulu3-70b-rlvr-awq"}


def bearish_share(key: str, arm: str) -> dict[str, float]:
    by = {}
    for node in (BENCH / key / arm).glob("rep*/*"):
        f = node / "01_sketches_valid.json"
        if f.exists():
            xs = [s["direction"] for s in json.loads(f.read_text()) if s.get("direction") in ("+", "-")]
            if xs:
                by.setdefault(node.name, []).extend(xs)
    return {d: sum(x == "-" for x in v) / len(v) for d, v in by.items()}


def g2(key: str, cov) -> dict:
    D, M = bearish_share(key, "D"), bearish_share(key, "M")
    df = cov.copy()
    df["y"] = [D.get(d, np.nan) - M.get(d, np.nan) for d in df.index]
    df = df.dropna(subset=["y", "usrec"])
    fit = sm.OLS(df["y"].values, sm.add_constant(df[["usrec"]].values)).fit(cov_type="HAC", cov_kwds={"maxlags": HAC_LAGS})
    b, se, t = float(fit.params[1]), float(fit.bse[1]), float(fit.tvalues[1])
    return {"key": key, "n_dates": int(len(df)), "n_recession": int(df["usrec"].sum()), "coef": b,
            "ci95": [b - 1.96 * se, b + 1.96 * se], "t": t,
            "reading": ("insufficient coverage" if len(df) < MIN_DATES else
                        "TRIGGER" if t >= T_CRIT else ("NEG*" if t <= -T_CRIT else "null")),
            "status": "prospective" if key in PROSPECTIVE else "post hoc"}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--keys", nargs="*")
    ap.add_argument("--md", type=Path)
    a = ap.parse_args()
    keys = a.keys or sorted(p.name for p in BENCH.iterdir() if (p / f"{p.name}_row.json").exists())
    cov = build_covariates([d for d in all_dates() if d <= WINDOW_END])
    rows = [g2(k, cov) for k in keys if (BENCH / k / f"{k}_row.json").exists()]
    hdr = "| row | dates (recession) | G2 coef [95% CI] | t (HAC 6) | reading | status |\n|---|---|---|---|---|---|"
    lines = [f"| {r['key']} | {r['n_dates']} ({r['n_recession']}) | {r['coef']*100:+.1f} [{r['ci95'][0]*100:+.1f}, {r['ci95'][1]*100:+.1f}] | {r['t']:+.2f} | {r['reading']} | {r['status']} |" for r in rows]
    out = "\n".join([hdr] + lines)
    print(out)
    if a.md:
        a.md.write_text("# BM-2c addendum G: whole-panel estimand G2 (generated by analyze_wholepanel.py; do not hand-edit)\n\n"
                        "G2 = coefficient of USREC in D-minus-M bearish share, dates <= 2023-12, HAC(6); pp per recession month.\n\n" + out + "\n")


if __name__ == "__main__":
    main()
