#!/usr/bin/env python
"""Generate paper2 ST-1 tables from the frozen *_st1_row.json files (single numeric source).

Writes paper2/latex/sections/tab_st1_estimands.tex and tab_st1_probes.tex.
Usage: make_st1_tables.py [--check]   --check = fail if either file would change (drift gate).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from hindsight_paths import REPO
from build_st_panel import REGIONS

ST1 = REPO / "hindsight/outputs/st1"
SEC = REPO / "hindsight/paper2/latex/sections"
ROWS = [("deepseek-v4-flash", "DeepSeek v4-flash"), ("gemini-2.5-flash-pooled", "Gemini 2.5 Flash (pooled)"),
        ("claude-sonnet-5", "Sonnet 5"), ("gpt-5.4-mini", "GPT-5.4-mini"), ("claude-haiku-4-5", "Haiku 4.5\\textsuperscript{g}")]
PROBE_ROWS = [("deepseek-v4-flash", "DeepSeek v4-flash"), ("gemini-2.5-flash-pooled", "Gemini 2.5 Flash (2 reps)"),
              ("claude-sonnet-5", "Claude Sonnet 5"), ("gpt-5.4-mini", "GPT-5.4-mini"), ("claude-haiku-4-5", "Claude Haiku 4.5")]
HDR = "% Generated by scripts/make_st1_tables.py from outputs/st1/<tag>/<tag>_st1_row.json -- do not hand-edit.\n"


def pp(x: float) -> str:
    s = f"{x*100:+.1f}"
    return s.replace("-", "$-$")


def ci(d: dict, lo="lo", hi="hi") -> str:
    return f"[{pp(d[lo])}, {pp(d[hi])}]"


def bold_if_excl(d: dict) -> str:
    v = pp(d["pt"])
    return f"\\textbf{{{v}}}" if (d["lo"] > 0 or d["hi"] < 0) else v


def estimands(rows: list[tuple[str, dict]]) -> str:
    L = [HDR, "\\begin{table}[tbp]", "\\centering", "\\footnotesize", "\\setlength{\\tabcolsep}{4pt}",
         "\\resizebox{\\linewidth}{!}{%", "\\begin{tabular}{@{}l" + "l" * len(rows) + "@{}}", "\\toprule",
         "Estimand & " + " & ".join(n for n, _ in rows) + " \\\\", "\\midrule"]
    def line(label, contrast, key, cl=False):   # city-cluster CIs are quoted in the text, not the table
        cells = []
        for _, r in rows:
            d = r[key]
            if not r.get("memory_gate", True):   # BM-1 convention: a row below the memory gate gets no reading
                cells.append("---\\textsuperscript{g}")
                continue
            cells.append(f"{bold_if_excl(d)} {ci(d)}" + (f" / {ci(d, 'clo', 'chi')}" if cl and "clo" in d else ""))
        L.append(f"{label} & " + " & ".join(cells) + " \\\\")
    line("E2 (time)", "$\\mathrm{Gap}(D)-\\mathrm{Gap}(M)$", "E2")
    line("E2$_\\ell$ (place)", "$\\mathrm{Gap}(L)-\\mathrm{Gap}(M)$", "E2L")
    line("E2$_{d\\ell}$ (joint)", "$\\mathrm{Gap}(DL)-\\mathrm{Gap}(M)$", "E2DL")
    line("INT", "E2$_{d\\ell}-$E2$-$E2$_\\ell$", "INT")
    L.append("\\midrule")
    line("relocation", "$\\mathrm{Gap}_{\\text{fake}}(S)-\\mathrm{Gap}_{\\text{fake}}(D)$", "relocation", cl=False)
    line("interference", "$\\mathrm{Gap}_{\\text{true}}(S)-\\mathrm{Gap}_{\\text{true}}(D)$", "interference", cl=False)
    line("E3$_\\ell$\\textsuperscript{w}", "$\\mathrm{Gap}_{\\text{fake}}(S)-\\mathrm{Gap}_{\\text{true}}(S)$", "E3L", cl=False)
    L.append("\\quad reference\\textsuperscript{w} & "
             + " & ".join(pp(r["E3L_ref_D"]) if r.get("memory_gate", True) else "---" for _, r in rows) + " \\\\")
    L.append("\\midrule")
    L.append("Gap(M) / Gap(D) & " + " & ".join(
        f"{pp(r['gaps']['M']['gap'])} / {pp(r['gaps']['D']['gap'])}" for _, r in rows) + " \\\\")
    L.append("Gap(L) / Gap(DL) & " + " & ".join(
        f"{pp(r['gaps']['L']['gap'])} / {pp(r['gaps']['DL']['gap'])}" for _, r in rows) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}}",
          "\\caption{ST-1 estimands (pp; bold = 95\\% CI excludes zero; contrasts defined in \\S\\ref{sec:st}). DeepSeek, Sonnet 5, GPT-5.4-mini and Haiku: one replicate; Gemini 2.5 Flash: two "
          "independent replicates pooled (each replicate is quoted in the text and drawn in Figure~\\ref{fig:st1}). \\textsuperscript{g}~below the memory gate (LAP-ST hit 0.439 against the 0.629 majority-class rate): no reading, raw gaps shown. First bracket: node-level paired bootstrap "
          "($B=10{,}000$); city-cluster intervals are quoted in the text. Spatial transplant is read from the two "
          "D-referenced contrasts, relocation and interference. \\textsuperscript{w}~the preregistered within-S form and "
          "the value it takes when the asserted place is ignored (the D arm's own fake-minus-true gap); "
          "Appendix~\\ref{app:st1}.}",
          "\\label{tab:st1}", "\\end{table}", ""]
    return "\n".join(L)


def probes(rows: list[tuple[str, dict]]) -> str:
    L = [HDR, "\\begin{table}[tbp]", "\\centering", "\\small", "\\setlength{\\tabcolsep}{4pt}",
         "\\resizebox{\\linewidth}{!}{%", "\\begin{tabular}{@{}l" + "rr" * len(rows) + "@{}}", "\\toprule",
         "City & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{n}}}" for n, _ in rows) + " \\\\",
         " & " + " & ".join("LAP recall & hit" for _ in rows) + " \\\\", "\\midrule"]
    for key in list(REGIONS) + ["ALL"]:
        name = REGIONS[key][3] if key in REGIONS else "\\textbf{All}"
        cells = []
        for _, r in rows:
            l = r["lap"].get(key)
            cells.append(f"{l['recall']:.2f} & {l['hit']:.2f}" if l else "--- & ---")
        L.append(f"{name} & " + " & ".join(cells) + " \\\\")
    L.append("\\midrule")
    L.append("REC-ST joint recovery & " + " & ".join(
        f"\\multicolumn{{2}}{{c}}{{{r['rec']['ALL']['joint']:.3f} (date$\\pm$3mo {r['rec']['ALL']['date3']:.2f}, city {r['rec']['ALL']['city']:.2f})}}"
        for _, r in rows) + " \\\\")
    gate = " & ".join(f"\\multicolumn{{2}}{{c}}{{{'PASS' if r['memory_gate'] else 'FAIL'} ({r['lap']['ALL']['hit']:.3f} $>$ {r['plus_share']:.3f})}}" for _, r in rows)
    L.append("memory gate & " + gate + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}}",
          "\\caption{ST-1 probes per city. LAP-ST recall = share of samples (20 per replicate) answering higher/lower; hit = agreement of the "
          "net recalled direction with the realized 4-week direction (gate: majority-class rate). REC-ST: the masked snapshot "
          "is shown and the model asked for (year-month, city); joint = both correct.}",
          "\\label{tab:st1probes}", "\\end{table}", ""]
    return "\n".join(L)


def main() -> None:
    rows = [(n, json.loads((ST1 / t / f"{t}_st1_row.json").read_text())) for t, n in ROWS]
    prow = [(n, json.loads((ST1 / t / f"{t}_st1_row.json").read_text())) for t, n in PROBE_ROWS]
    out = {SEC / "tab_st1_estimands.tex": estimands(rows), SEC / "tab_st1_probes.tex": probes(prow)}
    check = "--check" in sys.argv
    drift = False
    for path, txt in out.items():
        if check:
            if not path.exists() or path.read_text() != txt:
                print(f"DRIFT: {path.name}"); drift = True
        else:
            path.write_text(txt); print(f"wrote {path.name}")
    if check:
        sys.exit(1 if drift else 0)


if __name__ == "__main__":
    main()
