"""Gate the AGGREGATE numbers quoted in paper 1's prose against the frozen rows.

Why this exists. make_bench_rows.py --check guards the generated table blocks,
but paper 1's prose also quotes *aggregates* over those rows -- "E2 +14 to
+33pp", "magnitudes vary (17--42pp)", "measured cutoffs span 22 months". Those
are hand-written, and nothing checked them. That is not hypothetical: section
8.3 shipped "E2 +14 to +38pp; E3 +16 to +50pp" for the 2026 cohort long after
the sentence had been rescoped from "all triggering models" to "2026
generation". +38/+50 were Claude Haiku 4.5, a 2025 row. Paper 2's table is
public on arXiv, so anyone could have recomputed the range and found it did
not match our own data.

The failure mode is structural: the two papers are generated by different
scripts, so a rescoped sentence in one silently keeps numbers that only the
other's table can refute. This script closes that by re-deriving each quoted
aggregate from the frozen row JSONs and diffing against the .tex.

Gated cells are excluded from every aggregate, which is the point of gating
them. Run with --check to fail loudly (exit 1); default prints a report.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "hindsight" / "scripts"))

from bench_registry import MODELS  # noqa: E402

BENCH = REPO / "hindsight" / "outputs" / "bench"
SEC = REPO / "hindsight" / "paper" / "latex" / "sections"

# tolerance in pp: the prose rounds to whole points
TOL = 0.55


def rows() -> list[dict]:
    out = []
    for m in MODELS:
        r = json.loads((BENCH / m["key"] / f"{m['key']}_row.json").read_text())
        # lap_at_chance lives in the registry, not the row json: the raw
        # locator still emits a "cutoff" for a model whose recall is guessing,
        # and the table prints ---^g for exactly those rows. An aggregate over
        # cutoffs must use the same 12 recall-capable rows the prose does.
        out.append({"key": m["key"], "tex": m["tex"], "gen": m["gen"], "row": r,
                    "lap_at_chance": m.get("lap_at_chance", False)})
    return out


def significant(cell: dict) -> bool:
    """Significant AND not gated. A gated cell has no defensible estimate."""
    if cell.get("gated"):
        return False
    ci = cell.get("ci95") or []
    if len(ci) != 2 or any(c is None for c in ci):
        return False
    if any(c != c for c in ci):  # NaN
        return False
    return ci[0] > 0 or ci[1] < 0


def span(cells: list[dict]) -> tuple[float, float] | None:
    v = [c["est"] * 100 for c in cells if significant(c)]
    return (min(v), max(v)) if v else None


def check() -> list[str]:
    R = rows()
    fails: list[str] = []

    def cells(gen: int, metric: str) -> list[dict]:
        return [r["row"][metric] for r in R if r["gen"] == gen]

    # --- 8.3: the 2026 cohort's significant E2 / E3 ranges --------------
    txt = (SEC / "08_crossmodel.tex").read_text()
    m = re.search(r"E2 \+(\d+) to \+(\d+)pp; E3 \+(\d+) to \+(\d+)pp", txt)
    if not m:
        fails.append("8.3: could not find the '(E2 +a to +bpp; E3 +c to +dpp)' "
                     "pattern -- if the sentence was reworded, update this gate")
    else:
        quoted = [float(x) for x in m.groups()]
        for metric, lo_q, hi_q, label in (
            ("E2_date_trigger", quoted[0], quoted[1], "E2"),
            ("E3_transplant", quoted[2], quoted[3], "E3"),
        ):
            got = span(cells(2026, metric))
            if got is None:
                fails.append(f"8.3 {label}: no significant 2026 cells at all")
                continue
            if abs(got[0] - lo_q) > TOL or abs(got[1] - hi_q) > TOL:
                owners = [
                    f"{r['tex']} {r['row'][metric]['est']*100:+.1f}"
                    for r in R if r["gen"] == 2026 and significant(r["row"][metric])]
                fails.append(
                    f"8.3 {label}: prose says +{lo_q:.0f} to +{hi_q:.0f}pp, "
                    f"frozen 2026 rows give {got[0]:+.1f} to {got[1]:+.1f}pp "
                    f"[{', '.join(owners)}]")

    # --- 8.1: 'magnitudes vary (17--42pp)' over the causal-core trio -----
    m = re.search(r"magnitudes vary \((\d+)--(\d+)pp\)", txt)
    if m:
        trio = {"gemini-2.5-flash", "gemini-2.5-pro", "deepseek-v4-flash"}
        v = [r["row"]["E2_date_trigger"]["est"] * 100 for r in R if r["key"] in trio]
        lo_q, hi_q = (float(x) for x in m.groups())
        if abs(min(v) - lo_q) > TOL or abs(max(v) - hi_q) > TOL:
            fails.append(f"8.1: prose says {lo_q:.0f}--{hi_q:.0f}pp, the three "
                         f"causal-core rows give {min(v):.1f}--{max(v):.1f}pp")

    # --- 8.2: measured cutoffs span N months ----------------------------
    m = re.search(r"span \\textbf\{(\d+) months\} \((\d{4}-\d{2}) to (\d{4}-\d{2})\)", txt)
    if m:
        n_q, lo_q, hi_q = int(m.group(1)), m.group(2), m.group(3)
        cuts = sorted(
            r["row"]["LAP"]["empirical_cutoff"] for r in R
            if r["row"]["LAP"].get("empirical_cutoff") and not r["lap_at_chance"])
        if cuts:
            def months(a: str, b: str) -> int:
                ya, ma = int(a[:4]), int(a[5:7])
                yb, mb = int(b[:4]), int(b[5:7])
                return (yb - ya) * 12 + (mb - ma)
            got = months(cuts[0], cuts[-1])
            if got != n_q or cuts[0] != lo_q or cuts[-1] != hi_q:
                fails.append(f"8.2: prose says {n_q} months ({lo_q} to {hi_q}), "
                             f"frozen rows give {got} months ({cuts[0]} to {cuts[-1]})")

    # --- 8.1 / abstract: E1 null on 13 of 15 ----------------------------
    e1 = json.loads((REPO / "hindsight" / "outputs" / "review" / "bench_e1.json").read_text())
    n_sig = e1["n_significant"]
    n_ok = e1["n_models_estimated"]
    for f, pat in ((SEC / "08_crossmodel.tex", r"is null on \\textbf\{(\d+)\}"),
                   (SEC / "00_abstract.tex", r"null on (\d+) of (\d+) benchmark models")):
        t = f.read_text()
        mm = re.search(pat, t)
        if mm:
            claimed_null = int(mm.group(1))
            if claimed_null != n_ok - n_sig:
                fails.append(f"{f.name}: claims E1 null on {claimed_null}, "
                             f"bench_e1.json gives {n_ok - n_sig} of {n_ok}")
    return fails


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if any prose aggregate disagrees with the rows")
    a = ap.parse_args()
    fails = check()
    if fails:
        print("PROSE AGGREGATE DRIFT:")
        for f in fails:
            print("  FAIL:", f)
        sys.exit(1 if a.check else 0)
    print("prose aggregates OK: 2026 E2/E3 ranges, causal-core spread, "
          "cutoff span, and E1 null count all match the frozen rows")


if __name__ == "__main__":
    main()
