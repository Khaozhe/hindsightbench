#!/usr/bin/env python3
"""RV-1 (review response 1, paper 1): frozen analyses, zero new model calls.

  preshock     E2-form contrast on rule-based pre-shock vs control dates (prereg/RV1_preshock_dates.json):
               PS = [Gap_D(S,C) - Gap_M(S,C)], Gap_X(S,C) = bearish share of arm X on SHOCK minus on CONTROL
               (replicates pooled, sketch-level shares, analyze_fm1.gap). Date-level bootstrap B=10,000, seed 2026;
               also per replicate and replicate x date hierarchical.
  anachronism  named-event lexicon (prereg/RV1_lexicon.json) with first-public dates; a hit is a response at
               decision date t containing a term first public after t. Arms R, D, M (W is audited elsewhere).
  hier         E1, E2 (and E3 on the primary model) under (a) replicate x date, (b) episode-block,
               (c) replicate x episode-block bootstrap, B=10,000, seed 2026.

    python scripts/analyze_rv1.py preshock|anachronism|hier [--models flash pro deepseek] [--out outputs/review/...]
"""
from __future__ import annotations
import argparse, json, re, sys
from collections import defaultdict
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).parent))
from analyze_fm1 import CRISIS, CALM_YEARS, all_dates, gap, fake_map  # noqa: E402

H = Path(__file__).resolve().parents[1]
MODELS = {"flash": H / "outputs/fm1/gemini-2.5-flash", "pro": H / "outputs/bench/gemini-2.5-pro",
          "deepseek": H / "outputs/bench/deepseek-v4-flash"}
PRIMARY = "flash"
B, SEED = 10_000, 2026
EPISODES = {"GFC": [d for d in CRISIS if d[:4] in ("2008", "2009")], "COVID": [d for d in CRISIS if d[:4] == "2020"],
            "inflation": [d for d in CRISIS if d[:4] == "2022"]}
DATES = all_dates()
CALM = [d for d in DATES if d[:4] in CALM_YEARS]
CALM_BLOCKS = {y: [d for d in CALM if d[:4] == y] for y in sorted(CALM_YEARS)}


def reps_of(root: Path, arm: str) -> list[str]:
    return sorted(p.name for p in (root / arm).glob("rep*") if p.is_dir())


def load(root: Path, arm: str, rep: str) -> dict[str, list[str]]:
    by = defaultdict(list)
    for f in (root / arm / rep).glob("*/01_sketches_valid.json"):
        by[f.parent.name].extend(s["direction"] for s in json.loads(f.read_text()) if s.get("direction") in ("+", "-"))
    return by


def pool(ds: list[dict]) -> dict[str, list[str]]:
    out = defaultdict(list)
    for d in ds:
        for k, v in d.items():
            out[k].extend(v)
    return out


def ci(x):
    return float(np.percentile(x, 2.5)), float(np.percentile(x, 97.5))


def contrast(Darm, Marm, S, C):
    return (gap(Darm, S, C) - gap(Marm, S, C)) * 100


# ---------------------------------------------------------------- preshock
def preshock(models, out):
    spec = json.loads((H / "prereg/RV1_preshock_dates.json").read_text())
    res = {}
    for m in models:
        root = MODELS[m]; reps = sorted(set(reps_of(root, "D")) & set(reps_of(root, "M")))
        D = {r: load(root, "D", r) for r in reps}; M = {r: load(root, "M", r) for r in reps}
        Dp, Mp = pool(D.values()), pool(M.values())
        res[m] = {}
        for setname in ("primary", "sens_mild", "sens_severe"):
            S = [r["date"] for r in spec[setname]["SHOCK"]]; C = spec[setname]["CONTROL"]
            S = [d for d in S if Dp.get(d) and Mp.get(d)]; C = [d for d in C if Dp.get(d) and Mp.get(d)]
            est = contrast(Dp, Mp, S, C)
            rng = np.random.default_rng(SEED); Sa, Ca = np.array(S), np.array(C); bt = np.empty(B)
            for b in range(B):
                s, c = list(rng.choice(Sa, len(Sa))), list(rng.choice(Ca, len(Ca))); bt[b] = contrast(Dp, Mp, s, c)
            rng = np.random.default_rng(SEED); ht = np.empty(B)
            for b in range(B):
                rr = list(rng.choice(reps, len(reps)))
                Db, Mb = pool([D[r] for r in rr]), pool([M[r] for r in rr])
                s, c = list(rng.choice(Sa, len(Sa))), list(rng.choice(Ca, len(Ca))); ht[b] = contrast(Db, Mb, s, c)
            per_rep = {r: contrast(D[r], M[r], S, C) for r in reps}
            lo, hi = ci(bt)
            reading = "DETECTED" if lo > 0 else ("NEGATIVE*" if hi < 0 else ("BOUNDED (<10pp)" if hi < 10 else "INCONCLUSIVE"))
            res[m][setname] = {"n_shock": len(S), "n_control": len(C), "PS": est, "ci95_date": [lo, hi], "ci95_rep_x_date": list(ci(ht)),
                               "gap_D": gap(Dp, S, C) * 100, "gap_M": gap(Mp, S, C) * 100, "per_rep": per_rep, "reading": reading,
                               "reps": reps}
    L = ["# RV-1 pre-shock test (generated by analyze_rv1.py preshock; do not hand-edit)", "",
         "PS = Gap_D(S,C) - Gap_M(S,C), pp; S = rule-based pre-shock dates, C = calm-before-calm controls (prereg/RV1_preshock_dates.json).",
         "Readings (frozen): DETECTED = date-level CI > 0; BOUNDED = CI upper < +10pp; NEGATIVE* = CI < 0; else INCONCLUSIVE.", "",
         "| model | set | n S / C | Gap_D | Gap_M | PS [95% CI date] | [95% CI rep x date] | per replicate | reading |", "|---|---|---|---|---|---|---|---|---|"]
    for m, v in res.items():
        for sn, r in v.items():
            L.append(f"| {m}{' (primary)' if m == PRIMARY and sn == 'primary' else ''} | {sn} | {r['n_shock']} / {r['n_control']} | {r['gap_D']:+.1f} | {r['gap_M']:+.1f} | "
                     f"{r['PS']:+.1f} [{r['ci95_date'][0]:+.1f}, {r['ci95_date'][1]:+.1f}] | [{r['ci95_rep_x_date'][0]:+.1f}, {r['ci95_rep_x_date'][1]:+.1f}] | "
                     f"{', '.join(f'{x:+.1f}' for x in r['per_rep'].values())} | {r['reading']} |")
    emit(L, res, out)


# ---------------------------------------------------------------- anachronism
def anachronism(models, out):
    lex = json.loads((H / "prereg/RV1_lexicon.json").read_text())["terms"]
    pats = [(t["id"], re.compile(t["regex"], re.I), t["first_public"]) for t in lex]
    res, hits = {}, []
    for m in models:
        root = MODELS[m]; res[m] = {}
        for arm in ("R", "D", "M"):
            n = nh = 0; by_term = defaultdict(int)
            for rep in reps_of(root, arm):
                for f in (root / arm / rep).glob("*/04_raw_response.txt"):
                    t = f.parent.name
                    if t not in DATES:
                        continue
                    n += 1; txt = f.read_text(errors="ignore"); cell_hit = False
                    for tid, rx, first in pats:
                        if t < first:
                            for mt in rx.finditer(txt):
                                cell_hit = True; by_term[tid] += 1
                                a, b = max(0, mt.start() - 160), min(len(txt), mt.end() + 160)
                                hits.append({"model": m, "arm": arm, "rep": rep, "date": t, "term": tid, "first_public": first,
                                             "context": txt[a:b].replace("\n", " ")})
                    nh += cell_hit
            res[m][arm] = {"responses": n, "responses_with_hit": nh, "hits_by_term": dict(by_term)}
    L = ["# RV-1 anachronism audit (generated by analyze_rv1.py anachronism; do not hand-edit)", "",
         "A hit = a response at decision date t containing a lexicon term first public after t (prereg/RV1_lexicon.json).",
         "Raw regex hits; manual classification of every hit follows the frozen criteria in the prereg.", "",
         "| model | arm | responses | responses with >=1 hit | hits by term |", "|---|---|---|---|---|"]
    for m, v in res.items():
        for arm, r in v.items():
            L.append(f"| {m} | {arm} | {r['responses']} | {r['responses_with_hit']} | {r['hits_by_term'] or '-'} |")
    L += ["", f"## All hits ({len(hits)})", ""] + [f"- {h['model']} {h['arm']} {h['rep']} {h['date']} [{h['term']} > {h['first_public']}]: ...{h['context']}..." for h in hits]
    emit(L, {"summary": res, "hits": hits}, out)


# ---------------------------------------------------------------- hier
def hier(models, out):
    res = {}
    for m in models:
        root = MODELS[m]
        arms = {a: {r: load(root, a, r) for r in reps_of(root, a)} for a in "RDMW"}
        res[m] = {}
        for name, (x, y) in {"E1": ("R", "D"), "E2": ("D", "M")}.items():
            reps = sorted(set(arms[x]) & set(arms[y]))
            if len(reps) < 2:
                res[m][name] = {"note": f"fewer than 2 shared replicates ({reps})"}; continue
            X = {r: arms[x][r] for r in reps}; Y = {r: arms[y][r] for r in reps}
            est = contrast(pool(X.values()), pool(Y.values()), CRISIS, CALM)
            res[m][name] = {"est": est, "reps": reps, **boot_all(X, Y, reps)}
        if m == PRIMARY:
            reps = reps_of(root, "W"); fm = fake_map(DATES)
            Wf = {r: {fm[d]: v for d, v in arms["W"][r].items() if d in fm} for r in reps}
            Wt = {r: arms["W"][r] for r in reps}
            est = (gap(pool(Wf.values()), CRISIS, CALM) - gap(pool(Wt.values()), CRISIS, CALM)) * 100
            res[m]["E3"] = {"est": est, "reps": reps, **boot_all(Wf, Wt, reps)}
    L = ["# RV-1 hierarchical inference (generated by analyze_rv1.py hier; do not hand-edit)", "",
         "95% intervals, B = 10,000, seed 2026. date = paper's date-level bootstrap; rep x date = resample replicates then dates;",
         "episode = resample the 3 crisis episodes and 3 calm years, then dates within; rep x episode = both.", "",
         "| model | estimand | estimate (pp) | date | rep x date | episode | rep x episode | replicates |", "|---|---|---|---|---|---|---|---|"]
    f = lambda c: f"[{c[0]:+.1f}, {c[1]:+.1f}]"
    for m, v in res.items():
        for e, r in v.items():
            if "note" in r:
                L.append(f"| {m} | {e} | {r['note']} | | | | | |"); continue
            L.append(f"| {m} | {e} | {r['est']:+.1f} | {f(r['date'])} | {f(r['rep_x_date'])} | {f(r['episode'])} | {f(r['rep_x_episode'])} | {len(r['reps'])} |")
    emit(L, res, out)


def boot_all(X: dict, Y: dict, reps: list[str]) -> dict:
    Xp, Yp = pool(X.values()), pool(Y.values()); Ca, Za = np.array(CRISIS), np.array(CALM)
    ep = list(EPISODES.values()); cb = list(CALM_BLOCKS.values()); out = {}
    for mode in ("date", "rep_x_date", "episode", "rep_x_episode"):
        rng = np.random.default_rng(SEED); v = np.empty(B)
        for b in range(B):
            if mode.startswith("rep"):
                rr = list(rng.choice(reps, len(reps))); Xb, Yb = pool([X[r] for r in rr]), pool([Y[r] for r in rr])
            else:
                Xb, Yb = Xp, Yp
            if mode.endswith("episode"):
                cs = [d for i in rng.integers(0, len(ep), len(ep)) for d in rng.choice(ep[i], len(ep[i]))]
                qs = [d for i in rng.integers(0, len(cb), len(cb)) for d in rng.choice(cb[i], len(cb[i]))]
            else:
                cs, qs = list(rng.choice(Ca, len(Ca))), list(rng.choice(Za, len(Za)))
            v[b] = contrast(Xb, Yb, cs, qs)
        out[mode] = list(ci(v))
    return out


def emit(L, obj, out):
    txt = "\n".join(L) + "\n"; print(txt[:6000])
    if out:
        Path(out).write_text(txt); Path(out).with_suffix(".json").write_text(json.dumps(obj, indent=1, default=float))


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("what", choices=["preshock", "anachronism", "hier"])
    ap.add_argument("--models", nargs="*", default=["flash", "pro", "deepseek"]); ap.add_argument("--out")
    a = ap.parse_args()
    {"preshock": preshock, "anachronism": anachronism, "hier": hier}[a.what](a.models, a.out)
